CREATE TABLE students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    register_number VARCHAR(255) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL,
    phone_number VARCHAR(255) NOT NULL,
    department VARCHAR(255) NOT NULL,
    year_of_study INTEGER NOT NULL,
    gender VARCHAR(20) NOT NULL DEFAULT 'MALE'
);

CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_number VARCHAR(255) NOT NULL UNIQUE,
    building_name VARCHAR(255) NOT NULL,
    room_type VARCHAR(255) NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity >= 1),
    occupied_beds INTEGER NOT NULL DEFAULT 0 CHECK (occupied_beds >= 0),
    monthly_rent DOUBLE PRECISION NOT NULL,
    hostel_type VARCHAR(255) NOT NULL DEFAULT 'BOYS',
    status VARCHAR(255) NOT NULL DEFAULT 'AVAILABLE'
);

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    room_id BIGINT NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
    booking_date DATE NOT NULL,
    status VARCHAR(255) NOT NULL DEFAULT 'ACTIVE'
);

CREATE TABLE hostel_fees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    hostel_name VARCHAR(255) NOT NULL,
    room_number VARCHAR(255) NOT NULL,
    fee_type VARCHAR(255) NOT NULL,
    total_amount DOUBLE PRECISION NOT NULL,
    paid_amount DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    remaining_balance DOUBLE PRECISION NOT NULL,
    due_date DATE NOT NULL,
    payment_date DATE,
    payment_method VARCHAR(255),
    transaction_reference VARCHAR(255),
    status VARCHAR(255) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE payment_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fee_id BIGINT NOT NULL REFERENCES hostel_fees(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    amount DOUBLE PRECISION NOT NULL,
    payment_date DATE NOT NULL,
    payment_method VARCHAR(255) NOT NULL,
    transaction_reference VARCHAR(255) NOT NULL UNIQUE,
    receipt_number VARCHAR(255) NOT NULL UNIQUE,
    recorded_by VARCHAR(255) NOT NULL,
    notes VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE in_app_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_role VARCHAR(255) NOT NULL,
    student_id BIGINT REFERENCES students(id) ON DELETE CASCADE,
    fee_id BIGINT REFERENCES hostel_fees(id) ON DELETE SET NULL,
    category VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    link_url VARCHAR(255),
    dedup_key VARCHAR(255) UNIQUE,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE persons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL
);

CREATE TABLE student_persons (
    person_id BIGINT PRIMARY KEY REFERENCES persons(id) ON DELETE CASCADE,
    roll_number VARCHAR(255) NOT NULL,
    course VARCHAR(255) NOT NULL
);

CREATE INDEX idx_notif_student ON in_app_notifications(student_id);
CREATE INDEX idx_notif_role ON in_app_notifications(recipient_role);
CREATE INDEX idx_notif_dedup ON in_app_notifications(dedup_key);
CREATE INDEX idx_booking_student_status ON bookings(student_id, status);
CREATE INDEX idx_booking_room_status ON bookings(room_id, status);
CREATE INDEX idx_fee_due_date ON hostel_fees(due_date);
