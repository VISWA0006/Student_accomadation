CREATE TABLE user_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(120) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    student_id BIGINT UNIQUE REFERENCES students(id) ON DELETE CASCADE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    password_change_required BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_user_account_role CHECK (role IN ('ADMIN', 'STUDENT'))
);

CREATE TABLE maintenance_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    room_id BIGINT NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
    title VARCHAR(160) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    category VARCHAR(40) NOT NULL,
    priority VARCHAR(20) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'OPEN',
    resolution_note VARCHAR(2000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE room_waitlist_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    preferred_hostel_type VARCHAR(20) NOT NULL,
    preferred_room_type VARCHAR(100),
    status VARCHAR(20) NOT NULL DEFAULT 'WAITING',
    waiting_student_id BIGINT UNIQUE REFERENCES students(id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_waitlist_status CHECK (status IN ('WAITING', 'OFFERED', 'FULFILLED', 'CANCELLED'))
);

CREATE INDEX idx_waitlist_queue
    ON room_waitlist_entries(status, preferred_hostel_type, created_at);

CREATE TABLE accommodation_stays (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL UNIQUE REFERENCES bookings(id) ON DELETE RESTRICT,
    check_in_at TIMESTAMP,
    check_out_at TIMESTAMP,
    check_out_note VARCHAR(1000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_stay_dates CHECK (check_out_at IS NULL OR check_in_at IS NOT NULL)
);

