package com.accommodation.entity;

import jakarta.persistence.*;

/**
 * Demonstrates JPA/Hibernate Inheritance Mapping (JOINED strategy).
 * 
 * Parent entity: 'persons' table stores common personal attributes.
 * Joined strategy creates a separate table for the base class and each subclass,
 * linked by a shared primary key foreign key.
 */
@Entity
@Table(name = "persons")
@Inheritance(strategy = InheritanceType.JOINED)
public class Person {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "name", nullable = false)
    private String name;

    @Column(name = "email", nullable = false)
    private String email;

    public Person() {
    }

    public Person(String name, String email) {
        this.name = name;
        this.email = email;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }
}
